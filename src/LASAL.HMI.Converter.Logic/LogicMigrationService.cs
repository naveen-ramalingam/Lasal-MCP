using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using LASAL.HMI.Converter.Models;

namespace LASAL.HMI.Converter.Logic;

/// <summary>
/// Translates LASAL SCREEN FunctionBlocks (_INTER_NEU / LS0004.MPC), button/screen events,
/// and LASAL CLASS 2 _Global / _MyIO hooks into VISUDesigner FunctionBlocks and JavaScript CodeModules.
/// </summary>
public sealed class LogicMigrationService
{
    public LogicMigrationResult GenerateLogicArtifacts(HmiIntermediateModel model)
    {
        ArgumentNullException.ThrowIfNull(model);
        var result = new LogicMigrationResult();

        // 1. Generate main MigratedLogic.js CodeModule
        var jsSb = new StringBuilder();
        jsSb.AppendLine("/**");
        jsSb.AppendLine($" * Auto-generated by LASAL HMI Converter for project '{model.ProjectMetadata.ProjectName}'.");
        jsSb.AppendLine(" * Provides migrated LASAL SCREEN FunctionBlocks, screen/window navigation helpers,");
        jsSb.AppendLine(" * datapoint read/write wrappers, and custom unit conversion formulas.");
        jsSb.AppendLine(" */");
        jsSb.AppendLine("(function (global) {");
        jsSb.AppendLine("    'use strict';");
        jsSb.AppendLine();
        jsSb.AppendLine("    const LasalMigratedLogic = {");
        jsSb.AppendLine("        screenNumberToName: {");

        foreach (var scr in model.Screens)
        {
            jsSb.AppendLine($"            {scr.ScreenNumber}: \"{EscapeJs(scr.Name)}\",");
        }
        jsSb.AppendLine("        },");
        jsSb.AppendLine("        windowNumberToName: {");
        foreach (var win in model.Windows)
        {
            jsSb.AppendLine($"            {win.ScreenNumber}: \"{EscapeJs(win.Name)}\",");
        }
        jsSb.AppendLine("        },");
        jsSb.AppendLine();
        jsSb.AppendLine("        readDatapoint: function (dpId, fallback) {");
        jsSb.AppendLine("            try {");
        jsSb.AppendLine("                if (global.sig && global.sig.datapoints && typeof global.sig.datapoints.getValue === 'function') {");
        jsSb.AppendLine("                    return global.sig.datapoints.getValue(dpId);");
        jsSb.AppendLine("                }");
        jsSb.AppendLine("            } catch (e) { console.warn('readDatapoint error:', e); }");
        jsSb.AppendLine("            return fallback !== undefined ? fallback : 0;");
        jsSb.AppendLine("        },");
        jsSb.AppendLine();
        jsSb.AppendLine("        writeDatapoint: function (dpId, value) {");
        jsSb.AppendLine("            try {");
        jsSb.AppendLine("                if (global.sig && global.sig.datapoints && typeof global.sig.datapoints.setValue === 'function') {");
        jsSb.AppendLine("                    global.sig.datapoints.setValue(dpId, value);");
        jsSb.AppendLine("                    return true;");
        jsSb.AppendLine("                }");
        jsSb.AppendLine("            } catch (e) { console.warn('writeDatapoint error:', e); }");
        jsSb.AppendLine("            return false;");
        jsSb.AppendLine("        },");
        jsSb.AppendLine();
        jsSb.AppendLine("        toggleDatapoint: function (dpId, setVal, resetVal) {");
        jsSb.AppendLine("            const cur = this.readDatapoint(dpId, resetVal || 0);");
        jsSb.AppendLine("            const next = (cur == (setVal !== undefined ? setVal : 1)) ? (resetVal !== undefined ? resetVal : 0) : (setVal !== undefined ? setVal : 1);");
        jsSb.AppendLine("            return this.writeDatapoint(dpId, next);");
        jsSb.AppendLine("        },");
        jsSb.AppendLine();
        jsSb.AppendLine("        navigateScreenByNumber: function (screenNo) {");
        jsSb.AppendLine("            const target = this.screenNumberToName[screenNo] || ('Screen_' + screenNo);");
        jsSb.AppendLine("            if (global.sig && global.sig.navigation && typeof global.sig.navigation.openDashboard === 'function') {");
        jsSb.AppendLine("                global.sig.navigation.openDashboard(target);");
        jsSb.AppendLine("            }");
        jsSb.AppendLine("            return target;");
        jsSb.AppendLine("        },");
        jsSb.AppendLine();
        jsSb.AppendLine("        openWindowByNumber: function (windowNo) {");
        jsSb.AppendLine("            const target = this.windowNumberToName[windowNo] || ('Window_' + windowNo);");
        jsSb.AppendLine("            if (global.sig && global.sig.navigation && typeof global.sig.navigation.openWindow === 'function') {");
        jsSb.AppendLine("                global.sig.navigation.openWindow(target);");
        jsSb.AppendLine("            }");
        jsSb.AppendLine("            return target;");
        jsSb.AppendLine("        },");
        jsSb.AppendLine();
        jsSb.AppendLine("        closeActiveWindow: function () {");
        jsSb.AppendLine("            if (global.sig && global.sig.navigation && typeof global.sig.navigation.closeWindow === 'function') {");
        jsSb.AppendLine("                global.sig.navigation.closeWindow();");
        jsSb.AppendLine("            }");
        jsSb.AppendLine("        },");

        // Emit FunctionBlocks
        foreach (var fb in model.FunctionBlocks)
        {
            var fnName = SanitizeJsIdentifier(fb.Name);
            jsSb.AppendLine();
            jsSb.AppendLine($"        {fnName}: function () {{");
            var fbBody = BuildFunctionBlockJsBody(fb, "            ");
            jsSb.Append(fbBody);
            jsSb.AppendLine("        },");

            result.FunctionBlocks.Add(new GeneratedFunctionBlockArtifact(
                Name: fnName,
                Description: $"Migrated from LASAL SCREEN FunctionBlock '{fb.Name}' (#{fb.Index})",
                JavaScriptBody: fbBody));
        }

        jsSb.AppendLine("    };");
        jsSb.AppendLine();
        jsSb.AppendLine("    global.LasalMigratedLogic = LasalMigratedLogic;");
        jsSb.AppendLine("})(typeof window !== 'undefined' ? window : globalThis);");

        var mainModuleCode = jsSb.ToString();
        result.CodeModules["MigratedLogic.js"] = mainModuleCode;

        // 2. Generate CustomMyIoStubs.js if custom PLC UI classes were detected
        if (model.CustomPlcUiClasses.Count > 0)
        {
            var stubSb = new StringBuilder();
            stubSb.AppendLine("/**");
            stubSb.AppendLine(" * Custom LASAL CLASS 2 UI Classes (_MyIO / _ScrollArea2 / _Screen / _Global) Reference & Stubs.");
            stubSb.AppendLine(" */");
            stubSb.AppendLine("(function (global) {");
            stubSb.AppendLine("    'use strict';");
            stubSb.AppendLine("    const CustomPlcUiStubs = {");

            foreach (var customCls in model.CustomPlcUiClasses)
            {
                var safeCls = SanitizeJsIdentifier(customCls.ClassName);
                stubSb.AppendLine($"        // Class: {customCls.ClassName} : {customCls.BaseClassName} (Pattern: {customCls.InferredPattern})");
                stubSb.AppendLine($"        // Overridden ST Methods: {string.Join(", ", customCls.OverriddenMethods)}");
                stubSb.AppendLine($"        {safeCls}: {{");
                stubSb.AppendLine($"            baseClass: \"{EscapeJs(customCls.BaseClassName)}\",");
                stubSb.AppendLine($"            inferredPattern: \"{EscapeJs(customCls.InferredPattern)}\",");
                stubSb.AppendLine("            onRefresh: function (context) {");
                stubSb.AppendLine("                // Manual review stub for custom PLC-side _Grafix drawing");
                stubSb.AppendLine("                return true;");
                stubSb.AppendLine("            }");
                stubSb.AppendLine("        },");
            }

            stubSb.AppendLine("    };");
            stubSb.AppendLine("    global.CustomPlcUiStubs = CustomPlcUiStubs;");
            stubSb.AppendLine("})(typeof window !== 'undefined' ? window : globalThis);");
            result.CodeModules["CustomMyIoStubs.js"] = stubSb.ToString();
        }

        // 3. Validate all generated JS modules
        foreach (var (fileName, jsCode) in result.CodeModules)
        {
            var errors = ValidateJavaScriptSyntax(jsCode);
            foreach (var err in errors)
            {
                result.ValidationErrors.Add($"{fileName}: {err}");
            }
        }

        return result;
    }

    private static string BuildFunctionBlockJsBody(FunctionBlockModel fb, string indent)
    {
        var sb = new StringBuilder();
        var openIfCount = 0;

        foreach (var step in fb.Steps)
        {
            var curIndent = indent + new string(' ', openIfCount * 4);
            var op1Expr = FormatOperand(step.Input1DatapointId, step.Input1Constant);
            var op2Expr = FormatOperand(step.Input2DatapointId, step.Input2Constant);
            var outDp = step.Output1DatapointId ?? step.Input1DatapointId;

            switch (step.Opcode)
            {
                case "LseMirr":
                case "SetValue":
                    if (!string.IsNullOrEmpty(outDp))
                    {
                        sb.AppendLine($"{curIndent}this.writeDatapoint(\"{EscapeJs(outDp)}\", {op2Expr});");
                    }
                    break;

                case "Add":
                    if (!string.IsNullOrEmpty(outDp))
                    {
                        sb.AppendLine($"{curIndent}this.writeDatapoint(\"{EscapeJs(outDp)}\", ({op1Expr}) + ({op2Expr}));");
                    }
                    break;

                case "Sub":
                    if (!string.IsNullOrEmpty(outDp))
                    {
                        sb.AppendLine($"{curIndent}this.writeDatapoint(\"{EscapeJs(outDp)}\", ({op1Expr}) - ({op2Expr}));");
                    }
                    break;

                case "Inc":
                    if (!string.IsNullOrEmpty(outDp))
                    {
                        sb.AppendLine($"{curIndent}this.writeDatapoint(\"{EscapeJs(outDp)}\", ({op1Expr}) + 1);");
                    }
                    break;

                case "Dec":
                    if (!string.IsNullOrEmpty(outDp))
                    {
                        sb.AppendLine($"{curIndent}this.writeDatapoint(\"{EscapeJs(outDp)}\", ({op1Expr}) - 1);");
                    }
                    break;

                case "Toggle":
                    if (!string.IsNullOrEmpty(outDp))
                    {
                        sb.AppendLine($"{curIndent}this.toggleDatapoint(\"{EscapeJs(outDp)}\", 1, 0);");
                    }
                    break;

                case "Equal":
                    sb.AppendLine($"{curIndent}if (({op1Expr}) == ({op2Expr})) {{");
                    openIfCount++;
                    break;

                case "Greater":
                    sb.AppendLine($"{curIndent}if (({op1Expr}) > ({op2Expr})) {{");
                    openIfCount++;
                    break;

                case "Less":
                    sb.AppendLine($"{curIndent}if (({op1Expr}) < ({op2Expr})) {{");
                    openIfCount++;
                    break;

                case "Else":
                    if (openIfCount > 0)
                    {
                        var outerIndent = indent + new string(' ', (openIfCount - 1) * 4);
                        sb.AppendLine($"{outerIndent}}} else {{");
                    }
                    break;

                case "EndIf":
                    if (openIfCount > 0)
                    {
                        openIfCount--;
                        var outerIndent = indent + new string(' ', openIfCount * 4);
                        sb.AppendLine($"{outerIndent}}}");
                    }
                    break;

                case "CMD_NEWPICTURE":
                    sb.AppendLine($"{curIndent}this.navigateScreenByNumber({step.CommandArg ?? 0});");
                    break;

                case "CMD_NEWWINDOW":
                    sb.AppendLine($"{curIndent}this.openWindowByNumber({step.CommandArg ?? 0});");
                    break;

                case "CMD_CLOSE":
                case "CMD_RETURN":
                    sb.AppendLine($"{curIndent}this.closeActiveWindow();");
                    break;

                default:
                    sb.AppendLine($"{curIndent}// Step opcode: {step.Opcode}");
                    break;
            }
        }

        while (openIfCount > 0)
        {
            openIfCount--;
            var outerIndent = indent + new string(' ', openIfCount * 4);
            sb.AppendLine($"{outerIndent}}}");
        }

        if (sb.Length == 0)
        {
            sb.AppendLine($"{indent}return true;");
        }

        return sb.ToString();
    }

    private static string FormatOperand(string? dpId, double? constantVal)
    {
        if (!string.IsNullOrWhiteSpace(dpId))
        {
            return $"this.readDatapoint(\"{EscapeJs(dpId)}\", 0)";
        }
        if (constantVal.HasValue)
        {
            return constantVal.Value.ToString(CultureInfo.InvariantCulture);
        }
        return "0";
    }

    public static List<string> ValidateJavaScriptSyntax(string jsCode)
    {
        var errors = new List<string>();
        if (string.IsNullOrWhiteSpace(jsCode))
        {
            errors.Add("JavaScript module content is empty.");
            return errors;
        }

        int braces = 0, parens = 0, brackets = 0;
        var inString = false;
        var stringChar = '\0';
        var inLineComment = false;
        var inBlockComment = false;

        for (var i = 0; i < jsCode.Length; i++)
        {
            var c = jsCode[i];
            var next = i + 1 < jsCode.Length ? jsCode[i + 1] : '\0';

            if (inLineComment)
            {
                if (c == '\n') inLineComment = false;
                continue;
            }
            if (inBlockComment)
            {
                if (c == '*' && next == '/')
                {
                    inBlockComment = false;
                    i++;
                }
                continue;
            }
            if (inString)
            {
                if (c == '\\')
                {
                    i++;
                    continue;
                }
                if (c == stringChar)
                {
                    inString = false;
                }
                continue;
            }

            if (c == '/' && next == '/')
            {
                inLineComment = true;
                i++;
                continue;
            }
            if (c == '/' && next == '*')
            {
                inBlockComment = true;
                i++;
                continue;
            }
            if (c == '"' || c == '\'')
            {
                inString = true;
                stringChar = c;
                continue;
            }

            switch (c)
            {
                case '{': braces++; break;
                case '}': braces--; break;
                case '(': parens++; break;
                case ')': parens--; break;
                case '[': brackets++; break;
                case ']': brackets--; break;
            }

            if (braces < 0) errors.Add("Unmatched closing brace '}'.");
            if (parens < 0) errors.Add("Unmatched closing parenthesis ')'.");
            if (brackets < 0) errors.Add("Unmatched closing bracket ']'.");
        }

        if (inString) errors.Add("Unterminated string literal.");
        if (braces != 0) errors.Add($"Unbalanced curly braces (delta={braces}).");
        if (parens != 0) errors.Add($"Unbalanced parentheses (delta={parens}).");
        if (brackets != 0) errors.Add($"Unbalanced brackets (delta={brackets}).");

        return errors;
    }

    private static string SanitizeJsIdentifier(string raw)
    {
        if (string.IsNullOrWhiteSpace(raw)) return "fn_0";
        var sb = new StringBuilder(raw.Length);
        foreach (var ch in raw)
        {
            if (char.IsLetterOrDigit(ch) || ch == '_') sb.Append(ch);
            else sb.Append('_');
        }
        var res = sb.ToString();
        if (char.IsDigit(res[0])) res = "_" + res;
        return res;
    }

    private static string EscapeJs(string raw)
    {
        return raw.Replace("\\", "\\\\").Replace("\"", "\\\"");
    }
}

public sealed class LogicMigrationResult
{
    public Dictionary<string, string> CodeModules { get; } = new(StringComparer.OrdinalIgnoreCase);
    public List<GeneratedFunctionBlockArtifact> FunctionBlocks { get; } = new();
    public List<string> ValidationErrors { get; } = new();
}

public sealed record GeneratedFunctionBlockArtifact(
    string Name,
    string Description,
    string JavaScriptBody);
